package com.shop.api.service;

import com.shop.entity.SysOrder;
import com.shop.entity.SysRefund;

import java.math.BigDecimal;

/**
 * 下单这一路的余额支付：可用余额判够不够 + 冻结（下单）/ 结转（支付）/ 解冻（取消）/ 退回（退款），写在 shop-api。
 *
 * 和统一下单、用券、用分那几份放在一起、只写一份：钱是这个人在钱包上的资产，
 * 「这一单该从余额里占多少」只要有两套说法，买家账户上就会出现对不上的数。
 *
 * 四个动作跟着订单的四拍走，每一拍都在人家已有的那个事务里：
 * 1. {@link #apply} —— 算钱那一趟里判余额够不够（统一下单和下单试算共用），只读库不落库
 * 2. {@link #freeze} —— 主单已经落库，把这一单的实付从可用里冻进冻结（真下单才走，试算不走）
 * 3. {@link #settle} —— 支付回调：冻住的那一笔真扣走
 * 4. {@link #unfreeze} / {@link #giveBack} —— 单子没成交（取消）整笔退回；成交之后退了货按这张退款单的实退金额退回余额
 *
 * 余额只付「这一单的实付」这一整笔，不做部分支付：应付金额是 券抵扣 + 积分抵扣 折完剩下的那一份，
 * 页面让人自己填"用余额付多少"就会多出一个要跟着退款走的数，所以这一路只认 pay_type = 4 一档，
 * 占多少钱也就是 sys_order.pay_amount 那一格。
 *
 * 于是"这一单冻着多少钱"不另存一列：**sys_order.pay_type 落 4 就是这条链唯一的记号**，
 * 要还（取消）、要扣（支付回调）、要退（退款）读的都是这一行上的 pay_amount。
 * 这一列原本只由支付回调写，现在统一下单也写它（不写就冻不了钱），回调照旧拿实际渠道覆盖 ——
 * 所以下单选了余额、回调却报了别的渠道的话，{@link #settle} 当场拒（不然那一笔钱永远留在冻结里出不来）。
 *
 * 账上那几个数怎么动都在 ShopConsumerWalletMapper 那四条条件增量里（判据压在 WHERE 的
 * balance / frozen_balance >= 这一笔 上，返回 0 行就是这一笔占不着，报出去让整单回滚），
 * 这里只留两件事：把判据跑完说清是哪一格不够、把每一笔变动记成流水。
 * 唯一没有闸门的那一条是退款 —— 这一轮才建的账，追不到钱包上线之前支付的老单，那条按"能退就退、退不了就跳过"办。
 *
 * 流水只在**可用余额真的动了**的那三拍写（下单冻结 −、取消解冻 +、退款退回 +）；
 * 支付结转只是把冻结改成已消耗，balance 一分没动，所以那边不插流水（口径同积分的结转那一拍）。
 */
public interface ShopOrderWalletService {

    /**
     * 这一单该从余额里占多少钱（不是支付方式为余额、或者没有钱要付就返回 0）。
     *
     * 两道判据，不过就当场抛异常（宁可拒单，也不能"钱冻住了、订单却没落"或者反过来）：
     * - 账户被冻住（status 0）：这一本被冻就不该再拿余额付钱，早点和人说清
     * - 可用余额不够这一单的实付：报出"要付多少、账上还有多少"，让人换支付方式或者先充值
     *
     * 走在 {@link ShopOrderPointsService#apply} 之后（那一拍只判分），更走在支付回调之前：
     * 这里只读账户、只折个数，动账户是 {@link #freeze} 那一步。
     *
     * @param userId    下单人（sys_user.id）：钱包是这个人账户上的钱
     * @param payType   请求体里的支付方式（字典 pay_type），只有 4 余额走这一路
     * @param payAmount 这一单算完券和分之后的实付金额（sys_order.pay_amount）
     * @return 要冻结多少钱（不是余额支付、或者实付 ≤ 0 就是 0 元，后三拍在上面走都是零开销）
     */
    BigDecimal apply(Long userId, Integer payType, BigDecimal payAmount);

    /**
     * 冻结：把这一单的实付从可用余额挪进冻结余额，并记一笔「6 冻结」的流水（金额为负 —— 可用余额确实少了这一笔）。
     *
     * 必须在主单 insert 之后调（流水要落 biz_id / biz_no 是哪个订单），和下单同事务：
     * 冻结失败就整单回滚，不会出现"订单落了、钱没占住"或者反过来。
     * 抢不到那一行（并发下同一笔钱被别的订单占走、或者账户刚被冻住）报回去让买家重新提交。
     */
    void freeze(Long userId, SysOrder order, BigDecimal amount);

    /**
     * 支付回调那一拍：这一单冻住的钱真扣走（frozen → 累计消费，可用余额不再动，所以不记流水）。
     *
     * @param notifiedPayType 支付通知里报上来的渠道（{@link ShopOrderPaidService} 拿它覆盖主单上那一格）：
     *                        这一单原本是余额支付、这里报了别的渠道就当场拒 ——
     *                        上面那一覆盖，"这一单冻着钱包的钱"这个记号就没了，那一笔会永远留在冻结余额里
     */
    void settle(SysOrder order, Integer notifiedPayType);

    /**
     * 取消订单那一拍：整笔退回可用余额（frozen → balance），记一笔「7 解冻」的流水冲掉下单那一笔。
     *
     * 单没成交，钱没走、更不该花 —— 这一拍和退券、还库存、解冻积分是同一批要跟着取消一起还回去的东西。
     *
     * @return 退回了多少元（这一单不是余额支付就是 0）
     */
    BigDecimal unfreeze(SysOrder order);

    /**
     * 退款那一拍：这一张退款单实退的钱退回可用余额（累计消费 −、balance +），记一笔「3 退款」的流水。
     *
     * 只有支付方式为余额的那一单走这一路，其余三种渠道钱从原路退，不碰钱包。
     * 一张单分几批退就走几次，每次退的是那一张退款单自己的实退金额。
     * 这一条刻意没有闸门：这一轮才建的账追不到老单，没有账户行就返回 0 元跳过、不报错，
     * 钱该退还得退，退款不能因为钱包这边对不上而卡住。
     *
     * @param order  来源订单（读它的 pay_type 认这条链、读它的 user_id 知道是谁的钱）
     * @param refund 这张退款单（流水上落的单号和金额都取它，别拿订单那一格 —— 一单可能退好几次）
     * @param amount 这一张退款单实际退多少钱
     * @return 退回余额多少钱（0 = 这一单不是余额支付、或者这个人压根没有账户行）
     */
    BigDecimal giveBack(SysOrder order, SysRefund refund, BigDecimal amount);
}
