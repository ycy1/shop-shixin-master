package com.shop.api.service;

/**
 * 过期扫描：把"到点了但没人动过"的那几行状态摊平到 2 已过期
 *
 * 为什么走定时而不是在用的时候现判完事：现判那一处保留（任务按天跑，刚过期几个小时内库里还是 0，
 * 拿一张过期的券抵钱、放一张过期的票进园都是要拦的），但账面得有人每天摊一次 ——
 * 否则「用户票种」「优惠券发放记录」这两本列表上会一直躺着一堆看起来还能用的 0 未使用，
 * 运营要挑出"哪些该退款、哪些已经作废"只能自己按日期筛。
 *
 * 两条都是一条条件 UPDATE 收全平台：status = 0 压在 WHERE 里，已经用掉/作废/退过的绝不回头改状态，
 * 所以重复跑只补当天新进过窗口的那几行，是幂等的。
 */
public interface ShopExpireScanService {

    /**
     * 用户主题公园票：游玩日期过了当天、还从来没核销过 → 2 已过期
     *
     * @return 这次落成已过期的张数
     */
    int expireParkTickets();

    /**
     * 用户优惠券：过期时间已经过了、还没用也没作废 → 2 已过期
     *
     * @return 这次落成已过期的张数
     */
    int expireUserCoupons();
}
