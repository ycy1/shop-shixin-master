package com.shop.api.service;

import com.shop.entity.ShopTrendyCollectRecord;

/**
 * 潮玩系列「集齐」判定 + 奖励兑现（写入路只有这一份，住在 shop-api）
 *
 * 集齐判的是存量，不是"刚刚抽的那一下"：一个人在某条系列名下抽到过的**规格种类数**，
 * 够不够这条系列当前的规格总数（跨所有盲盒、跨多轮，空奖不算，同一种规格抽到三次只算一种）。
 * 这种数挂在抽盒那一步上没有意义（每抽一次都要把全系列的记录数一遍，公网库一趟一趟地往返），
 * 所以判定放在<b>人来领的那一刻</b>现做一遍（一轮一条 SQL 只比这一（人，系列）组合）——
 * 原来是定时任务一轮扫全平台、扫到就发，2026-10-30 改成图鉴页上那颗「领取奖励」，
 * 因为奖励什么时候到账由人决定，比由调度器决定更好解释（也不用为它留一条 cron）。
 *
 * 为什么住在 shop-api 而不是 shop-admin：兑现要的积分账户、券模板占量、发通知那三件套都在这一端
 *（徽章的发放、签到、购物送分都在这一端），而 shop-api 摸不到后台的 service；系列那一页只负责把
 * reward_type / reward_value 两格配置写进库，不参与发。
 *
 * 幂等靠 shop_trendy_collect_record 那一行（uk_trendy_user 一人一条系列一行）：
 * 先插记录、插成功了才兑现，撞唯一键就是"这一笔已经领过了"，一分一券都不再发 ——
 * 反过来先兑现就会出现"券已经到卡包、记录行插不进去"。两个人同时点同一份、或者页面重复提交，
 * 都是后到的那一个撞在唯一键上拿到"已经领过了"，不会双发。
 *
 * 上线之前就已经集齐过的人不用补数据：判定比的是存量，他一进图鉴页就能看到「可领取」，点一次就补齐。
 *
 * 容错方向和原来那条任务一样是<b>尽力而为</b>吗？不是 —— 现在是同步一次点击，
 * 兑现失败（券模板被删、发行量占满、实物那件没配券）只把原因写进这一行的 reward_desc 并回一句给用户，
 * 不回滚那一行领取记录：那一行回滚了人就能再点一次，但重复点也领不到第二份东西，说明反而丢了。
 * 所以三档奖励的"配置对不对"仍由后台保存那一侧先拦（见 shop-admin 的 ShopTrendyServiceImpl#validate）。
 */
public interface ShopTrendyCollectRewardService {

    /**
     * 领取这一条系列上的集齐奖励（页面上那颗按钮，谁领的按登录态取）。
     *
     * 一句判定 SQL 先确认「这个人、这条系列」够线、奖励配齐、还没领过，回得来的一行就是要插的那一行；
     * 然后先插记录（撞 uk_trendy_user 就是已经领过，报错回去）、再按 reward_type 分三档兑现：
     * 1 积分（账户原子加分 + 一笔「13 潮玩集齐」流水）、2 优惠券（占那张模板的发行额度、落用户券快照）、
     * 3 实物（发一张圈得住那件商品的代金券，履约还是靠下单用券那一条链，本期没有实物出库），
     * 最后发一句集齐通知。
     *
     * @param trendyId 要领哪一条系列的奖励
     * @return 刚落库的那一行（reward_desc 是这一笔兑现成了什么，页面直接把那句念出来）
     */
    ShopTrendyCollectRecord claim(Long trendyId);
}
