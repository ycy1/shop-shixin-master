package com.shop.api.service;

import com.shop.dto.wallet.ShopWalletChangeDto;
import com.shop.entity.ShopConsumerWallet;

/**
 * 钱包的充值 / 提现（两端共用，所以住在 shop-api 的 comm 那一路）。
 *
 * 这两颗是**往账上真收钱、真把钱拿走**的动作，和 {@link ShopOrderWalletService} 那四拍是一套的：
 * 那一本只管"这一单占多少钱、什么时候花掉、什么时候还回去"，钱从哪儿来、到哪儿去是这里这两条。
 * 所以两边共用同一条规矩：账户上的数只由带闸门的条件增量 UPDATE 改，每一笔跟着写一行流水，
 * 全在同一个事务里 —— 绝不做"读回来加一下再写回去"那种两步动作。
 *
 * 动的都是登录这个人自己那本账：/api/** 不过 Sa-Token 拦截器，所以服务层自己取登录态，
 * 取不到就报"请先登录后再…"，入参里也没有 userId 这一格（前端传谁的 id 都不认）。
 *
 * 还有一处和下单那一路不同：**充值是这张表第一行账的来路**。冻结那条 SQL 压着
 * balance >= 这一笔，没有账户行就是 0 元、占不到钱，所以之前"没有余额的人走到下单那一拍就被拦下"；
 * 现在他先充值，那一行账由第一次真收钱的动作带出来（uk_user 钉住一人一行，建账撞了就改走增量）。
 * 提现反过来：没开账就是没有钱可提，不会在这儿建账。
 */
public interface ShopWalletService {

    /**
     * 充值：可用余额和累计充值一起加这一笔，记一行「1 充值」的流水（金额为正）。
     *
     * 判据只有金额那一头（要大于 0、最多两位小数）：账户被冻住也照样收得进钱，
     * 冻结说的是"这一本不能被动用"，不是"钱不能进来"。
     * 本期这一笔不涉及真收款的渠道（微信支付那条充值单链还没接，订单类型 4 那一档还没落地），
     * 所以流水上这一笔不挂单据：biz_id / biz_no 留空，谁充的记在 create_by、为什么充记在说明里。
     *
     * @return 改完之后的账户行（前端拿它刷新那三个数，不用再调一次读接口）
     */
    ShopConsumerWallet recharge(ShopWalletChangeDto form);

    /**
     * 提现：可用余额减、累计提现加同一笔，记一行「4 提现」的流水（金额为负）。
     *
     * 三道判据，说清是哪一种：压根没开账 / 账户被冻住 / 可用余额不够这一笔
     *（下单没付的单子占着的那一部分在 frozen_balance 上，那一份提不走）。
     * 抢不到那一行（同一刻这一笔刚被下单冻结或者另一趟提现用掉）报回去让人重新提交。
     *
     * 和充值一样，这一笔本期不建提现单：钱从账上核销掉、走的是线下那一路，
     * 要查谁什么时候提了多少，翻流水那一行就够了。
     *
     * @return 改完之后的账户行
     */
    ShopConsumerWallet withdraw(ShopWalletChangeDto form);
}
