package com.shop.api.service;

import com.shop.dto.activity.ShopActivityBadgeGiveDto;
import com.shop.entity.ShopActivityBadge;

import java.time.LocalDateTime;

/**
 * 徽章达标判定 + 发放（写入路共用这一份，住在 shop-api）
 *
 * 放在 shop-api 而不是 shop-admin 的理由和积分、用券那几份一样：签到的写入和支付回调都住在这一端，
 * 而这一端摸不到后台的 service；两边各写一套"这一枚到没到位、发出去要兑现什么"，
 * 就会出现同一个徽章在页面上下发和用户买满之后各发一半，账户上的分和券也对不上。
 *
 * 三条路是（2026-10-18 起自动那两条都不挂在业务动作上了，全走定时任务，见 {@code TaskQuartzBadge}）：
 * 1. {@link #grantSigninBadges} —— 定时任务，一次判完全平台的 3 签到徽章（比的是累计签到天数）
 * 2. {@link #grantPurchaseBadges} —— 定时任务，一次判完全平台的 1 门店（逐家比在这家店买过的件数）
 *    和 4 消费（比全平台件数）徽章
 * 3. {@link #grantToUsers} —— 后台「徽章管理」列表上那颗「下发」，谁都能发、不看达标线
 *
 * 一枚徽章一个人只有一行（uk_badge_user），所以前两条自动路每一轮任务都可以整批重跑：
 * 到位了又还没拿到的那几枚才发，已经拿到的那一行撞唯一键就跳过。兑现（加分、发券）只跟着
 * "第一次落到这个人手上"那一次做一次，任务重复跑、网关重复推送都不会多发一笔分。
 *
 * 发出去的那一刻顺带把定义表上那两格奖励兑现掉：points 走积分账户的原子增量 + 一笔「11 徽章发放」的流水，
 * coupon_ids 逐个发到这个人名下（占各张模板的发行额度、建用户券快照，口径同后台优惠券那页的「发放」）。
 *
 * 自动那两条和手动那一条的**容错方向相反**，这是定死的：
 * 自动那一路（定时任务）兑现是"尽力而为"—— 券模板被删了、发行量不够了，就跳过那一张券、徽章照发，
 * 绝不能因为一个人的一张券把整轮任务顶回去；手动那一路反过来要报错回滚，
 * 运营点「下发」结果什么都没发到还看不出来，比少发一张券严重得多。
 */
public interface ShopActivityBadgeGrantService {

    /**
     * 定时任务那一条：一次判完全平台的 3 签到徽章（谁名下签到行数够到哪一枚的达标线、又还没拿到过）。
     *
     * 从签到那一步搬出来是因为签到那条链的耗时全在来回数上（MySQL 在公网那台机器上）：判定要在同一个
     * 事务里多跑"取候选 + 落徽章行 + 兑现分和券"好几趟，而这一档比的是累计签了几天 —— 那个数按天才有变化，
     * 晚上几分钟发没有任何影响，所以一轮任务跑一次就够。
     *
     * 天数不在这里数：批量那条 SQL 在 HAVING 里就把达标线比完了，回到服务里的每一行都是要发的
     *（一行 = 一枚徽章 + 该发给谁，见 {@code ShopActivityBadgeMapper#selectSigninBadgeHits}）。
     *
     * 这一路没有"就是今天这一签"那一条记录，所以徽章行的 source_id 和积分流水的 biz_id 都留 NULL
     *（和后台手工下发同形）；来源照样落 1 系统发放。
     *
     * @return 这一轮实发几枚（够线但已经被别的动作发过的那些不计）
     */
    int grantSigninBadges();

    /**
     * 定时任务那一条：一次判完全平台的 1 门店 + 4 消费徽章（谁买够件数、又还没拿到过对应的那几枚）。
     *
     * 原来挂在支付回调上判：一次回调要先按这一单铺到的每家店各捞一趟候选、再各数一次存量。
     * 这两件事比的都不是"这一单买了多少"而是这个人名下的累计件数，所以和签到那一档同处理 ——
     * 一轮任务一条 SQL 把全平台比完，回调那条链少掉好几趟公网往返。
     *
     * 件数同样在 SQL 里比完（按（人，店）聚成派生表再联徽章，见 {@code
     * ShopActivityBadgeMapper#selectPurchaseBadgeHits}），回到服务里的每一行就是要发的。
     *
     * 搬进任务带来一个口径变化要说清楚：**判定不再只跟着"刚刚付款的那几家店"走**，
     * 每轮都全平台重算一遍，所以以前付款时还没建好、后来才配上的门店/消费徽章，
     * 以及这一版上线之前那些老订单，也会在下一轮补齐到手上（原来那一版错过就永远错过了）。
     *
     * 这一路同样没有"就是这一单"那一条单据，所以徽章行的 source_id/source_no 和积分流水的
     * biz_id/biz_no 都留 NULL；来源照样落 3 消费达标（门店和消费两类共用这一档，字典里没有"门店"）。
     *
     * @return 这一轮实发几枚
     */
    int grantPurchaseBadges();

    /**
     * 后台那颗「下发」：把一枚徽章手工发给一批人，不看达标线，也允许发给还没拿到过的人以外的情况（已有的跳过）。
     *
     * 整批一个事务，奖励兑现是**严格**的：券模板没了、发行量不够、有效期算不出来都直接报错回滚，
     * 不留下"徽章发了、券没发"的半批。
     *
     * @return 实发人数（请求里那批人减去本来就持有这一枚的那些）
     */
    int grantToUsers(ShopActivityBadgeGiveDto form);

    /**
     * 发一枚徽章给一个人（三条路最后都汇到这一格）。
     *
     * 先落那一行（唯一键就是"一人一枚"那道闸），落成功了才兑现 —— 反过来会出"券发出去了、
     * 徽章行撞唯一键被回滚"。已经拿到过（撞唯一键）返回 false，什么都不兑现。
     *
     * 这一格不接"来源单据"那两参：三条路都给不出可指的那一张单（自动那两条 2026-10-18 起住进定时任务，
     * 一轮任务里几十个人几张单；手工下发本来就没有单据），所以明细表的 source_id/source_no
     * 和积分流水的 biz_id/biz_no 一律留 NULL，认来源只看 source 那一格。
     *
     * @param endTime 这一枚什么时候过期，NULL = 永久；只有「下发」那一路给得出这一格
     *                （定义表上没有有效期列，自动那两条路发出去就是永久的）
     */
    boolean grant(ShopActivityBadge badge, Long userId, int source,
                  LocalDateTime endTime, boolean strictRewards);
}
